import type { CSSProperties, ImgHTMLAttributes } from "react";

type ImageSource = string | { src: string; width: number; height: number };

type ImageProps = Omit<ImgHTMLAttributes<HTMLImageElement>, "src" | "width" | "height"> & {
  src: ImageSource;
  alt: string;
  width?: number;
  height?: number;
  /** Fill the nearest positioned ancestor (like next/image `fill`). */
  fill?: boolean;
  /** Above-the-fold image: load eagerly with high fetch priority. */
  priority?: boolean;
  /** Accepted for next/image compatibility; ignored. */
  placeholder?: string;
  quality?: number;
};

// Must match WIDTHS in scripts/optimize-images.mjs.
const WIDTHS = [640, 1080, 1920];
const RASTER = /\.(png|jpe?g)$/i;
const SKIP = /^\/(favicon|android-chrome|apple-touch-icon|general-og)/;

const variant = (url: string, width: number) => {
  const withoutExt = url.replace(RASTER, "");
  return `/_opt${withoutExt}-${width}.webp`;
};

const fillStyle: CSSProperties = {
  position: "absolute",
  inset: 0,
  width: "100%",
  height: "100%",
};

/**
 * Drop-in replacement for next/image. Images under /public are served from the
 * responsive WebP variants generated by scripts/optimize-images.mjs; imported
 * assets and remote URLs are rendered as-is.
 */
export function Image({ src, alt, width, height, fill, priority, sizes, loading, style, placeholder: _placeholder, quality: _quality, ...rest }: ImageProps) {
  const url = typeof src === "string" ? src : src.src;
  const optimizable = typeof src === "string" && url.startsWith("/") && RASTER.test(url) && !SKIP.test(url);

  const w = width ?? (typeof src === "object" ? src.width : undefined);
  const h = height ?? (typeof src === "object" ? src.height : undefined);

  return (
    <img
      {...rest}
      src={optimizable ? variant(url, WIDTHS[WIDTHS.length - 1]) : url}
      srcSet={optimizable ? WIDTHS.map((x) => `${variant(url, x)} ${x}w`).join(", ") : undefined}
      sizes={optimizable ? (sizes ?? "100vw") : undefined}
      alt={alt}
      width={fill ? undefined : w}
      height={fill ? undefined : h}
      loading={priority ? "eager" : (loading ?? "lazy")}
      decoding="async"
      // React 19 supports the camelCase prop; browsers get the `fetchpriority` attribute.
      fetchPriority={priority ? "high" : undefined}
      style={fill ? { ...fillStyle, ...style } : style}
    />
  );
}

export default Image;
